    private void configurarFormulari() {
        setTitle(Textes.get("lloguer.tornar.title"));

        jLabelNomJoc.setText(Textes.get("lloguer.tornar.joc"));
        jLabelNomUsuari.setText(Textes.get("lloguer.tornar.usuari"));
        jLabelNomPlataforma.setText(Textes.get("lloguer.tornar.plataforma"));
        jLabelDataInici.setText(Textes.get("lloguer.tornar.data.inici"));
        jButtonJocRetornat.setText(Textes.get("boto.retornat"));
        jButtonTancar.setText(Textes.get("boto.tancar"));

        configurarTaula();

        jTextFieldNomJoc.setEditable(false);
        jTextFieldUsuari.setEditable(false);
        jTextFieldPlataforma.setEditable(false);
        jTextFieldDataInici.setEditable(false);
        jTextFieldNomJoc.setFocusable(false);
        jTextFieldUsuari.setFocusable(false);
        jTextFieldPlataforma.setFocusable(false);
        jTextFieldDataInici.setFocusable(false);

        carregarLloguersActius();
    }

    private void configurarTaula() {
        modelTaula = new DefaultTableModel(new Object[][]{}, new String[]{
            Textes.get("col.num"),
            Textes.get("col.titol"),
            Textes.get("col.usuari"),
            Textes.get("col.plataforma"),
            Textes.get("col.inici")
        }) {
            @Override
            public boolean isCellEditable(int rowIndex, int columnIndex) {
                return false;
            }
        };

        taulaLloguersActius.setModel(modelTaula);
        taulaLloguersActius.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        taulaLloguersActius.setRowHeight(24);
        taulaLloguersActius.getSelectionModel().addListSelectionListener(evt -> {
            if (!evt.getValueIsAdjusting()) {
                mostrarDetallSeleccionat();
            }
        });
    }

    private void carregarLloguersActius() {
        modelTaula.setRowCount(0);
        lloguersActius.clear();
        netejarDetall();

        for (Lloguer lloguer : gestor.getLloguersActius()) {
            lloguersActius.add(lloguer);
            modelTaula.addRow(new Object[]{
                lloguer.getNumeroRegistre(),
                lloguer.getJoc().getNom(),
                lloguer.getUsuari().getNomComplet(),
                lloguer.getPlataforma().getNom(),
                lloguer.getDataInici().format(FORMAT_DATA)
            });
        }

        jButtonJocRetornat.setEnabled(modelTaula.getRowCount() > 0);
    }

    private void mostrarDetallSeleccionat() {
        int fila = taulaLloguersActius.getSelectedRow();
        if (fila < 0) {
            netejarDetall();
            return;
        }

        int filaModel = taulaLloguersActius.convertRowIndexToModel(fila);
        if (filaModel < 0 || filaModel >= lloguersActius.size()) {
            netejarDetall();
            return;
        }

        Lloguer lloguer = lloguersActius.get(filaModel);
        jTextFieldNomJoc.setText(lloguer.getJoc().getNom());
        jTextFieldUsuari.setText(lloguer.getUsuari().getNomComplet());
        jTextFieldPlataforma.setText(lloguer.getPlataforma().getNom());
        jTextFieldDataInici.setText(lloguer.getDataInici().format(FORMAT_DATA));
    }

    private void netejarDetall() {
        jTextFieldNomJoc.setText("");
        jTextFieldUsuari.setText("");
        jTextFieldPlataforma.setText("");
        jTextFieldDataInici.setText("");
    }

    private void registrarRetorn() {
        int fila = taulaLloguersActius.getSelectedRow();
        if (fila < 0) {
            mostrarError(Textes.get("error.seleccio.lloguer"));
            return;
        }

        int filaModel = taulaLloguersActius.convertRowIndexToModel(fila);
        if (filaModel < 0 || filaModel >= lloguersActius.size()) {
            mostrarError(Textes.get("error.lloguer.no.trobat"));
            return;
        }

        Lloguer lloguer = lloguersActius.get(filaModel);

        int resposta = JOptionPane.showConfirmDialog(this,
                Textes.format("confirm.retorn", lloguer.getJoc().getNom(), lloguer.getUsuari().getNomComplet()),
                Textes.get("dialog.confirmacio"),
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            gestor.registrarRetorn(lloguer);
            JOptionPane.showMessageDialog(this,
                    Textes.get("info.retorn.registrat"),
                    Textes.get("dialog.informacio"),
                    JOptionPane.INFORMATION_MESSAGE);
            carregarLloguersActius();
        } catch (ReglaNegociException ex) {
            mostrarError(Textes.get(ex.getClau()));
        }
    }

    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge,
                Textes.get("dialog.error"), JOptionPane.ERROR_MESSAGE);
    }

