    /**
     * Actualitza el gènere i les unitats disponibles segons el joc seleccionat.
     * Només es poden triar les plataformes en què el joc s'ofereix i té estoc.
     */
    private void actualitzarPerJoc() {
        int index = jComboBoxSeleccioJoc.getSelectedIndex();
        Joc joc = (index >= 0 && index < jocs.size()) ? jocs.get(index) : null;

        for (Plataforma plataforma : Plataforma.values()) {
            JRadioButton radio = radios.get(plataforma);
            JTextField camp = campsUnitats.get(plataforma);
            if (radio == null || camp == null) {
                continue;
            }

            boolean disponible = joc != null && joc.tePlataforma(plataforma);
            int estoc = disponible ? joc.getEstoc(plataforma) : 0;

            radio.setEnabled(disponible && estoc > 0);
            camp.setText(String.valueOf(estoc));

            if (!radio.isEnabled() && radio.isSelected()) {
                grupPlataformes.clearSelection();
            }
        }

        jTextFieldGenereJoc.setText(joc == null ? "" : joc.getGenere().getNom());

        StringBuilder unitats = new StringBuilder();
        if (joc != null) {
            for (Plataforma plataforma : new Plataforma[]{Plataforma.PC, Plataforma.PS5,
                    Plataforma.XBOX, Plataforma.SWITCH2}) {
                if (!joc.tePlataforma(plataforma)) {
                    continue;
                }
                if (unitats.length() > 0) {
                    unitats.append('\n');
                }
                int estoc = joc.getEstoc(plataforma);
                String clau = estoc == 1
                        ? "plataforma.unitats.singular"
                        : "plataforma.unitats.plural";
                unitats.append(Textes.format(clau, plataforma.getNom(), estoc));
            }
        }
        jTextArea1.setText(unitats.toString());
        jTextArea1.setCaretPosition(0);
    }

    private void actualitzarBotoConfirmar() {
        if (jButtonConfirmar == null) {
            return;
        }
        boolean teUsuari = jComboBoxUsuaris.getSelectedIndex() >= 0
                && jComboBoxUsuaris.getSelectedIndex() < usuaris.size();
        boolean teJoc = jComboBoxSeleccioJoc.getSelectedIndex() >= 0
                && jComboBoxSeleccioJoc.getSelectedIndex() < jocs.size();
        jButtonConfirmar.setEnabled(teUsuari && teJoc && getPlataformaSeleccionada() != null);
    }

    private Plataforma getPlataformaSeleccionada() {
        for (Map.Entry<Plataforma, JRadioButton> entry : radios.entrySet()) {
            JRadioButton radio = entry.getValue();
            if (radio.isSelected() && radio.isEnabled()) {
                return entry.getKey();
            }
        }
        return null;
    }

    private void confirmarLloguer() {
        int indexUsuari = jComboBoxUsuaris.getSelectedIndex();
        int indexJoc = jComboBoxSeleccioJoc.getSelectedIndex();

        Usuari usuari = (indexUsuari >= 0 && indexUsuari < usuaris.size())
                ? usuaris.get(indexUsuari) : null;
        Joc joc = (indexJoc >= 0 && indexJoc < jocs.size())
                ? jocs.get(indexJoc) : null;
        Plataforma plataforma = getPlataformaSeleccionada();

        if (usuari == null || joc == null || plataforma == null) {
            mostrarError(Textes.get("error.seleccio.obligatoria"));
            return;
        }

        try {
            gestor.registrarLloguer(usuari, joc, plataforma);
            JOptionPane.showMessageDialog(this,
                    Textes.get("info.lloguer.registrat"),
                    Textes.get("dialog.informacio"),
                    JOptionPane.INFORMATION_MESSAGE);
            dispose();
        } catch (ReglaNegociException ex) {
            mostrarError(Textes.get(ex.getClau()));
            actualitzarPerJoc();
            actualitzarBotoConfirmar();
        }
    }

    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge,
                Textes.get("dialog.error"), JOptionPane.ERROR_MESSAGE);
    }

