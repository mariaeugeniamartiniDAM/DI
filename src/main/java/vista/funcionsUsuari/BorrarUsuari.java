    /**
     * Omple el combo d'usuaris, aplica els textos i connecta el botó de
     * tancar, que no té esdeveniment generat al formulari.
     */
    private void configurarFormulari() {
        setTitle(Textes.get("usuari.borrar.title"));
        jLabelSeleccioUsuari.setText(Textes.get("usuari.seleccio"));
        botoBorrar.setText(Textes.get("boto.esborrar"));
        botoTancar.setText(Textes.get("boto.tancar"));

        botoTancar.addActionListener(evt -> dispose());
        carregarUsuaris();
    }

    private void carregarUsuaris() {
        DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
        for (Usuari usuari : gestor.getUsuaris()) {
            model.addElement(usuari.getNomComplet());
        }
        jComboBoxSeleccioUsuari.setModel(model);
        botoBorrar.setEnabled(model.getSize() > 0);
    }

    private void esborrarUsuari() {
        int index = jComboBoxSeleccioUsuari.getSelectedIndex();
        Usuari usuari = (index >= 0 && index < gestor.getUsuaris().size())
                ? gestor.getUsuaris().get(index) : null;

        if (usuari == null) {
            mostrarError(Textes.get("error.usuari.no.trobat"));
            return;
        }

        if (gestor.teLloguersActius(usuari)) {
            mostrarError(Textes.get("error.usuari.amb.lloguers"));
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this,
                Textes.format("confirm.esborrar.usuari", usuari.getNomComplet()),
                Textes.get("dialog.confirmacio"),
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            gestor.esborrarUsuari(usuari);
            JOptionPane.showMessageDialog(this,
                    Textes.get("info.usuari.esborrat"),
                    Textes.get("dialog.informacio"),
                    JOptionPane.INFORMATION_MESSAGE);
            carregarUsuaris();
        } catch (ReglaNegociException ex) {
            mostrarError(Textes.get(ex.getClau()));
        }
    }

    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge,
                Textes.get("dialog.error"), JOptionPane.ERROR_MESSAGE);
    }

