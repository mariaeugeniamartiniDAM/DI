    /**
     * Omple el combo de jocs, aplica els textos i connecta el botó d'esborrar,
     * que no té esdeveniment generat al formulari.
     */
    private void configurarFormulari() {
        setTitle(Textes.get("joc.borrar.title"));
        jLabelSeleccioJoc.setText(Textes.get("joc.seleccio"));
        botoEsborrar.setText(Textes.get("boto.esborrar"));
        botoTancar.setText(Textes.get("boto.tancar"));

        botoEsborrar.addActionListener(evt -> esborrarJoc());
        carregarJocs();
    }

    private void carregarJocs() {
        DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
        for (Joc joc : gestor.getJocs()) {
            model.addElement(joc.getNom());
        }
        jComboBoxSeleccioJoc.setModel(model);
        botoEsborrar.setEnabled(model.getSize() > 0);
    }

    private void esborrarJoc() {
        int index = jComboBoxSeleccioJoc.getSelectedIndex();
        Joc joc = (index >= 0 && index < gestor.getJocs().size())
                ? gestor.getJocs().get(index) : null;

        if (joc == null) {
            mostrarError(Textes.get("error.joc.no.trobat"));
            return;
        }

        if (gestor.teLloguersActius(joc)) {
            mostrarError(Textes.get("error.joc.amb.lloguers"));
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this,
                Textes.format("confirm.esborrar.joc", joc.getNom()),
                Textes.get("dialog.confirmacio"),
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);

        if (resposta != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            gestor.esborrarJoc(joc);
            JOptionPane.showMessageDialog(this,
                    Textes.get("info.joc.esborrat"),
                    Textes.get("dialog.informacio"),
                    JOptionPane.INFORMATION_MESSAGE);
            carregarJocs();
        } catch (ReglaNegociException ex) {
            mostrarError(Textes.get(ex.getClau()));
        }
    }

    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge,
                Textes.get("dialog.error"), JOptionPane.ERROR_MESSAGE);
    }

