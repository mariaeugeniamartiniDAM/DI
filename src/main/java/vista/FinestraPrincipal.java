    /**
     * Prepara la taula amb el model propi i el renderitzador de colors.
     */
    private void configurarTaula() {
        String[] columnes = {
            Textes.get("col.num"),
            Textes.get("col.titol"),
            Textes.get("col.usuari"),
            Textes.get("col.plataforma"),
            Textes.get("col.inici"),
            Textes.get("col.tornada"),
            Textes.get("col.genere")
        };

        modelTaula = new DefaultTableModel(columnes, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        taulaLloguers.setModel(modelTaula);
        taulaLloguers.setDefaultRenderer(Object.class, new RenderitzadorLloguers());
        taulaLloguers.setAutoCreateRowSorter(true);
        taulaLloguers.setRowHeight(24);
        taulaLloguers.getTableHeader().setReorderingAllowed(false);

        setTitle(Textes.get("app.title"));
        jLabelTotalLloguers.setText(Textes.get("main.total"));
        jTextFieldsSumaLloguers.setEditable(false);
        jTextFieldsSumaLloguers.setFocusable(false);
    }

