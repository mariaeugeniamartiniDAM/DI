    /**
     * Refresca la taula i el comptador a partir del gestor de dades.
     */
    private void actualitzarVistes() {
        modelTaula.setRowCount(0);
        lloguersTaula.clear();

        for (Lloguer lloguer : gestor.getLloguersOrdenatsDesc()) {
            lloguersTaula.add(lloguer);
            modelTaula.addRow(new Object[]{
                lloguer.getNumeroRegistre(),
                lloguer.getJoc().getNom(),
                lloguer.getUsuari().getNomComplet(),
                lloguer.getPlataforma().getNom(),
                lloguer.getDataInici().format(formatData),
                lloguer.getDataTornadaPrevista().format(formatData),
                lloguer.getJoc().getGenere().getNom()
            });
        }

        jTextFieldsSumaLloguers.setText(String.valueOf(gestor.getLloguers().size()));
    }

    /**
     * Pinta cada fila segons l'estat del lloguer:
     *  - verd si ja s'ha retornat
     *  - vermell si està vençut
     */
    private final class RenderitzadorLloguers extends DefaultTableCellRenderer {

        private static final long serialVersionUID = 1L;

        @Override
        public Component getTableCellRendererComponent(JTable taula, Object valor,
                boolean seleccionada, boolean teFocus, int fila, int columna) {

            Component component = super.getTableCellRendererComponent(
                    taula, valor, seleccionada, teFocus, fila, columna);

            if (seleccionada) {
                component.setBackground(taula.getSelectionBackground());
                component.setForeground(taula.getSelectionForeground());
                return component;
            }

            if (fila < 0 || fila >= lloguersTaula.size()) {
                return component;
            }

            int filaModel = taula.convertRowIndexToModel(fila);
            if (filaModel < 0 || filaModel >= lloguersTaula.size()) {
                return component;
            }

            Lloguer lloguer = lloguersTaula.get(filaModel);
            if (lloguer.isRetornat()) {
                component.setBackground(new Color(205, 240, 205));
            } else if (lloguer.isVencut()) {
                component.setBackground(new Color(255, 205, 205));
            } else {
                component.setBackground(taula.getBackground());
            }
            component.setForeground(Color.BLACK);
            return component;
        }
    }

